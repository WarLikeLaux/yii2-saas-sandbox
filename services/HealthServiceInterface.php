<?php

declare(strict_types=1);

namespace app\services;

/**
 * Контракт сервиса проверки состояния инфраструктуры.
 *
 * Прячет за собой низкоуровневый компонент проверки (прогон проб и агрегацию)
 * и отдаёт вызывающему коду цельный отчёт. Благодаря этому контроллеры и
 * команды зависят от одной операции, а не от связки методов компонента.
 */
interface HealthServiceInterface
{
    /**
     * Прогоняет проверки инфраструктуры и собирает готовый отчёт о состоянии.
     *
     * @return HealthReport Срез состояния: результаты проверок, признак здоровья и статус
     */
    public function report(): HealthReport;
}
