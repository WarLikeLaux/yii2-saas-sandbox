<?php

declare(strict_types=1);

namespace app\helpers;

/**
 * Помощник для низкоуровневых операций с SQL и базой данных.
 *
 * Инкапсулирует повторяемую подготовку значений для запросов, чтобы сервисы не
 * держали у себя технические детали работы с SQL-шаблонами.
 */
class DbHelper
{
    /**
     * Экранирует спецсимволы `LIKE` (`%`, `_`, `\`) в пользовательском вводе.
     *
     * @param string $value Исходная подстрока
     * @return string Подстрока, безопасная для подстановки в шаблон `LIKE`
     */
    public function escapeLike(string $value): string
    {
        return strtr($value, ['\\' => '\\\\', '%' => '\\%', '_' => '\\_']);
    }
}
