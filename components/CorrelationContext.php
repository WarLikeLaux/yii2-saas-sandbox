<?php

declare(strict_types=1);

namespace app\components;

/**
 * Контекст корреляции: единый идентификатор для сквозной трассировки запроса.
 *
 * Одно событие в омниканальном сервисе проходит цепочку «HTTP-запрос → очередь →
 * воркер → внешний вызов». Чтобы в логах эту цепочку можно было собрать в одну
 * нить, ей присваивается **correlation id**: web-слой генерирует его (или берёт
 * из заголовка `X-Request-Id`), кладёт в задачу, а воркер восстанавливает — и
 * все логи на пути несут один и тот же идентификатор.
 *
 * Регистрируется синглтоном в контейнере, поэтому в пределах одного процесса
 * (запроса или задачи) все потребители видят один и тот же контекст.
 */
class CorrelationContext
{
    /**
     * @var string Текущий идентификатор корреляции (пустой, пока не задан)
     */
    private $id = '';

    /**
     * Возвращает текущий идентификатор корреляции.
     *
     * @return string Идентификатор или пустая строка, если ещё не задан
     */
    public function get(): string
    {
        return $this->id;
    }

    /**
     * Устанавливает идентификатор корреляции (например, из заголовка запроса
     * или из полей пришедшей задачи).
     *
     * @param string $id Идентификатор корреляции
     */
    public function set(string $id): void
    {
        $this->id = $id;
    }

    /**
     * Возвращает текущий идентификатор, сгенерировав новый, если он ещё не задан.
     *
     * @return string Гарантированно непустой идентификатор корреляции
     */
    public function ensure(): string
    {
        if ($this->id === '') {
            $this->id = bin2hex(random_bytes(8));
        }

        return $this->id;
    }
}
